  label:     { type: String,  required: true },
  icon:      { type: String,  default: 'user' },
  collapsed: { type: Boolean, default: false },
  badge:     { default: null },
})

const route      = useRoute()
const isActive   = computed(() => props.to !== '/' && route.path.startsWith(props.to) || route.path === props.to)
const badgeCount = computed(() => {
  if (!props.badge) return 0
  if (typeof props.badge === 'object' && 'value' in props.badge) return props.badge.value || 0
  return Number(props.badge) || 0
})
